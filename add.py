def add_numbers(a, b):
    """
    Adds two numbers and returns their sum.
    
    Args:
        a (int/float): First number
        b (int/float): Second number
    
    Returns:
        int/float: Sum of the two numbers
    """
    return a + b

# Example usage
result = add_numbers(5, 3)
print(f"Sum: {result}")  # Output: Sum: 8
